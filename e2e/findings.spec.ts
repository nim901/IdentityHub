import { expect, test } from "@playwright/test";
import { readFile } from "node:fs/promises";

test("@jira creates a finding and displays it in recent tickets", async ({ page }, testInfo) => {
  await page.route("https://auth.atlassian.com/**", async route => {
    const url = new URL(route.request().url());
    const callback = new URL(url.searchParams.get("redirect_uri")!);
    callback.searchParams.set("code", "fake-code");
    callback.searchParams.set("state", url.searchParams.get("state")!);
    await route.fulfill({ status: 302, headers: { location: callback.toString() } });
  });
  await page.goto("/");
  await page.getByLabel("Email").fill("finding-e2e@example.test");
  await page.getByLabel("Password").fill("example-password-123");
  await page.getByRole("button", { name: "Create account" }).click();
  await expect(page.getByRole("status")).toContainText("Account created");
  await page.getByRole("button", { name: "Sign in" }).click();
  await page.getByRole("button", { name: "Settings", exact: true }).click();
  await page.getByRole("button", { name: "Connect Jira" }).click();
  await page.getByLabel("Jira site").selectOption("site-one");
  await page.getByRole("button", { name: "Save site" }).click();
  await expect(page.getByText("Site selected.")).toBeVisible();
  await page.getByRole("button", { name: "Findings", exact: true }).click();
  await page.getByLabel("Jira project").selectOption("ONE");
  await expect(page.getByText("No tickets yet")).toBeVisible();
  await page.getByRole("button", { name: /report finding/i }).click();
  await page.getByLabel("Finding title").fill("Exposed service account");
  await page.getByLabel("Description").fill("An access key was exposed.");
  let release!: () => void;
  let started!: () => void;
  const blocked = new Promise<void>(resolve => { release = resolve; });
  const requestStarted = new Promise<void>(resolve => { started = resolve; });
  let posts = 0;
  let idempotencyKey = "";
  await page.route("**/api/findings", async route => {
    if (route.request().method() !== "POST") return route.continue();
    posts++;
    idempotencyKey = route.request().headers()["idempotency-key"] ?? "";
    expect(route.request().postDataJSON().siteId).toBe("site-one");
    started();
    await blocked;
    await route.continue();
  });
  await page.getByRole("button", { name: "Create ticket" }).click();
  await requestStarted;
  await expect(page.getByRole("button", { name: "Creating…" })).toBeDisabled();
  expect(posts).toBe(1);
  expect(idempotencyKey).toMatch(/^[a-f0-9]{32}$/);
  release();
  await expect(page.getByText("Exposed service account")).toBeVisible();
  const link = page.getByRole("link", { name: /ONE-1/ });
  await expect(link).toHaveAttribute("href", "https://example.atlassian.net/browse/ONE-1");
  await expect(link).toHaveAttribute("target", "_blank");
  await expect(link).toHaveAttribute("rel", /noopener/);
  await page.setViewportSize({ width: 375, height: 812 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(375);
  await page.screenshot({ path: testInfo.outputPath("tickets-mobile.png"), fullPage: true });
  let historyTitle = "Unsafe link";
  await page.route("**/api/findings?*", route => route.fulfill({ json: { findings: [{ issueKey: "ONE-9", title: historyTitle, createdAt: "2026-01-01T00:00:00.000Z", url: "https://attacker.example/browse/ONE-9" }] } }));
  await page.getByLabel("Jira project").selectOption("");
  await page.getByLabel("Jira project").selectOption("ONE");
  await expect(page.getByText("Unsafe link")).toBeVisible();
  await expect(page.getByRole("link", { name: "ONE-9" })).toHaveCount(0);
  historyTitle = "Added in another tab";
  await page.evaluate(() => window.dispatchEvent(new Event("focus")));
  await expect(page.getByText("Added in another tab")).toBeVisible();
  let releaseStatus!: () => void;
  let statusStarted!: () => void;
  const statusBlocked = new Promise<void>(resolve => { releaseStatus = resolve; });
  const statusRequest = new Promise<void>(resolve => { statusStarted = resolve; });
  await page.route("**/api/jira/status", async route => {
    statusStarted();
    await statusBlocked;
    await route.fulfill({ json: { configured: true, connected: true, site: { id: "site-two", name: "Other workspace", url: "https://other.atlassian.net" } } });
  }, { times: 1 });
  await page.route("**/api/findings?*", route => route.fulfill({ json: { findings: [{ issueKey: "ONE-8", title: "Other site ticket", createdAt: "2026-01-01T00:00:00.000Z", url: "https://other.atlassian.net/browse/ONE-8" }] } }));
  await page.evaluate(() => window.dispatchEvent(new Event("focus")));
  await statusRequest;
  await expect(page.getByText("Loading recent tickets…")).toBeVisible();
  await expect(page.getByText("Other site ticket")).toHaveCount(0);
  releaseStatus();
  await expect(page.getByText("Other workspace")).toBeVisible();
  await expect(page.getByText("Other site ticket")).toHaveCount(0);
});

test("@jira preserves the draft and blocks duplicate writes after an unknown result", async ({ page }) => {
  await page.route("https://auth.atlassian.com/**", async route => {
    const url = new URL(route.request().url());
    const callback = new URL(url.searchParams.get("redirect_uri")!);
    callback.searchParams.set("code", "fake-code");
    callback.searchParams.set("state", url.searchParams.get("state")!);
    await route.fulfill({ status: 302, headers: { location: callback.toString() } });
  });
  await page.goto("/");
  await page.getByLabel("Email").fill("finding-failures@example.test");
  await page.getByLabel("Password").fill("example-password-123");
  await page.getByRole("button", { name: "Create account" }).click();
  await expect(page.getByRole("status")).toContainText("Account created");
  await page.getByRole("button", { name: "Sign in" }).click();
  await page.getByRole("button", { name: "Settings", exact: true }).click();
  await page.getByRole("button", { name: "Connect Jira" }).click();
  await page.getByLabel("Jira site").selectOption("site-one");
  await page.getByRole("button", { name: "Save site" }).click();
  await expect(page.getByText("Site selected.")).toBeVisible();
  await page.getByRole("button", { name: "Findings", exact: true }).click();
  await page.getByLabel("Jira project").selectOption("ONE");
  await page.getByRole("button", { name: /report finding/i }).click();
  await page.getByLabel("Finding title").fill("Rejected finding");
  await page.getByLabel("Description").fill("Example description");
  const log = process.env.E2E_FAKE_REQUEST_LOG!;
  const countWrites = async () => (await readFile(log, "utf8").catch(() => "")).split("\n").filter(line => line === "issue_write").length;
  const beforeMismatch = await countWrites();
  await page.route("**/api/findings", route => {
    const body = route.request().postDataJSON();
    return route.continue({ postData: JSON.stringify({ ...body, siteId: "other-site" }) });
  }, { times: 1 });
  await page.getByRole("button", { name: "Create ticket" }).click();
  await expect(page.getByRole("alert")).toContainText("Jira site changed. No ticket was created");
  expect(await countWrites()).toBe(beforeMismatch);
  await page.getByRole("button", { name: "Create ticket" }).click();
  await expect(page.getByRole("alert")).toContainText("did not create");
  await expect(page.getByLabel("Finding title")).toHaveValue("Rejected finding");
  await page.route("**/api/findings", route => route.fulfill({ status: 502, json: { error: "Jira created the issue, but local recording failed. Do not retry.", issueKey: "ONE-44" } }), { times: 1 });
  await page.getByLabel("Finding title").fill("Recorded remotely");
  await page.getByRole("button", { name: "Create ticket" }).click();
  await expect(page.getByRole("alert")).toContainText("Jira created ONE-44");
  await page.getByLabel(/I checked Jira/).check();
  await page.route("**/api/findings", route => route.fulfill({ status: 401, body: "Proxy denied the response" }), { times: 1 });
  await page.getByLabel("Finding title").fill("Ambiguous authentication response");
  await page.getByRole("button", { name: "Create ticket" }).click();
  await expect(page.getByRole("alert")).toContainText("outcome is unknown");
  await expect(page.getByLabel("Finding title")).toHaveValue("Ambiguous authentication response");
  await page.getByLabel(/I checked Jira/).check();
  await page.route("**/api/findings", route => route.fulfill({ status: 403, body: "Proxy denied the response" }), { times: 1 });
  await page.getByLabel("Finding title").fill("Ambiguous proxy response");
  await page.getByRole("button", { name: "Create ticket" }).click();
  await expect(page.getByRole("alert")).toContainText("outcome is unknown");
  await page.getByLabel(/I checked Jira/).check();
  await page.getByLabel("Finding title").fill("Unknown outcome");
  let posts = 0;
  page.on("request", request => { if (new URL(request.url()).pathname === "/api/findings" && request.method() === "POST") posts++; });
  await page.getByRole("button", { name: "Create ticket" }).click();
  await expect(page.getByRole("alert")).toContainText("outcome is unknown");
  await expect(page.getByLabel("Finding title")).toHaveValue("Unknown outcome");
  await expect(page.getByRole("button", { name: "Create ticket" })).toBeDisabled();
  expect(posts).toBe(1);
  await page.getByLabel(/I checked Jira/).check();
  await expect(page.getByRole("button", { name: "Create ticket" })).toBeEnabled();
});

test("@jira an account change during submission does not send a write under the new account", async ({ page, context }) => {
  await page.route("https://auth.atlassian.com/**", async route => {
    const url = new URL(route.request().url());
    const callback = new URL(url.searchParams.get("redirect_uri")!);
    callback.searchParams.set("code", "fake-code");
    callback.searchParams.set("state", url.searchParams.get("state")!);
    await route.fulfill({ status: 302, headers: { location: callback.toString() } });
  });
  await page.goto("/");
  for (const email of ["writer-a@example.test", "writer-b@example.test"]) {
    await page.getByLabel("Email").fill(email);
    await page.getByLabel("Password").fill("example-password-123");
    await page.getByRole("button", { name: "Create account" }).click();
    await expect(page.getByRole("status")).toContainText("Account created");
  }
  await page.getByLabel("Email").fill("writer-a@example.test");
  await page.getByRole("button", { name: "Sign in" }).click();
  await page.getByRole("button", { name: "Settings", exact: true }).click();
  await page.getByRole("button", { name: "Connect Jira" }).click();
  await page.getByLabel("Jira site").selectOption("site-one");
  await page.getByRole("button", { name: "Save site" }).click();
  await expect(page.getByText("Site selected.")).toBeVisible();
  await page.getByRole("button", { name: "Findings", exact: true }).click();
  await page.getByLabel("Jira project").selectOption("ONE");
  await page.getByRole("button", { name: /report finding/i }).click();
  await page.getByLabel("Finding title").fill("First account private finding");
  await page.getByLabel("Description").fill("Private description");
  let release!: () => void;
  let started!: () => void;
  const blocked = new Promise<void>(resolve => { release = resolve; });
  const requestStarted = new Promise<void>(resolve => { started = resolve; });
  await page.route("**/api/findings", async route => {
    if (route.request().method() !== "POST") return route.continue();
    started();
    await blocked;
    await route.continue();
  });
  const log = process.env.E2E_FAKE_REQUEST_LOG!;
  const writesBefore = (await readFile(log, "utf8").catch(() => "")).split("\n").filter(line => line === "issue_write").length;
  await page.getByRole("button", { name: "Create ticket" }).click();
  await requestStarted;
  const other = await context.newPage();
  await other.goto("/");
  await other.getByRole("button", { name: /writer-a@example.test/ }).click();
  await other.getByRole("menuitem", { name: "Sign out" }).click();
  await other.getByLabel("Email").fill("writer-b@example.test");
  await other.getByLabel("Password").fill("example-password-123");
  await other.getByRole("button", { name: "Sign in" }).click();
  await expect(other.getByRole("button", { name: /writer-b@example.test/ })).toBeVisible();
  await page.bringToFront();
  await page.evaluate(() => window.dispatchEvent(new Event("focus")));
  await expect(page.getByRole("button", { name: /writer-b@example.test/ }).or(page.getByRole("button", { name: "Sign in" }))).toBeVisible();
  const response = page.waitForResponse(response => new URL(response.url()).pathname === "/api/findings" && response.request().method() === "POST");
  release();
  expect([401, 403]).toContain((await response).status());
  const writesAfter = (await readFile(log, "utf8").catch(() => "")).split("\n").filter(line => line === "issue_write").length;
  expect(writesAfter).toBe(writesBefore);
  await expect(page.getByText("First account private finding")).toHaveCount(0);
  await expect(page.getByRole("alert")).toContainText("check Jira");
});

test("@jira a lost response after a fake Jira write does not trigger another write", async ({ page }) => {
  await page.route("https://auth.atlassian.com/**", async route => {
    const url = new URL(route.request().url());
    const callback = new URL(url.searchParams.get("redirect_uri")!);
    callback.searchParams.set("code", "fake-code");
    callback.searchParams.set("state", url.searchParams.get("state")!);
    await route.fulfill({ status: 302, headers: { location: callback.toString() } });
  });
  await page.goto("/");
  await page.getByLabel("Email").fill("lost-response@example.test");
  await page.getByLabel("Password").fill("example-password-123");
  await page.getByRole("button", { name: "Create account" }).click();
  await expect(page.getByRole("status")).toContainText("Account created");
  await page.getByRole("button", { name: "Sign in" }).click();
  await page.getByRole("button", { name: "Settings", exact: true }).click();
  await page.getByRole("button", { name: "Connect Jira" }).click();
  await page.getByLabel("Jira site").selectOption("site-one");
  await page.getByRole("button", { name: "Save site" }).click();
  await expect(page.getByText("Site selected.")).toBeVisible();
  await page.getByRole("button", { name: "Findings", exact: true }).click();
  await page.getByLabel("Jira project").selectOption("ONE");
  await page.getByRole("button", { name: /report finding/i }).click();
  await page.getByLabel("Finding title").fill("Lost response finding");
  await page.getByLabel("Description").fill("The response will be lost.");
  const log = process.env.E2E_FAKE_REQUEST_LOG!;
  const countWrites = async () => (await readFile(log, "utf8").catch(() => "")).split("\n").filter(line => line === "issue_write").length;
  const before = await countWrites();
  let forwardedStatus = 0;
  await page.route("**/api/findings", async route => {
    if (route.request().method() !== "POST") return route.continue();
    const response = await route.fetch({ maxRetries: 0 });
    forwardedStatus = response.status();
    await route.abort();
  });
  await page.getByRole("button", { name: "Create ticket" }).click();
  await expect(page.getByRole("alert")).toContainText("outcome is unknown");
  expect(forwardedStatus).toBe(201);
  expect(await countWrites()).toBe(before + 1);
  await expect(page.getByLabel("Finding title")).toHaveValue("Lost response finding");
  await expect(page.getByRole("button", { name: "Create ticket" })).toBeDisabled();
});
