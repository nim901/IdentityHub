import { expect, test } from "@playwright/test";
import { readFileSync } from "node:fs";

test("@scanner a user issues and revokes a key used by an external scanner", async ({ page, request }) => {
  await page.route("https://auth.atlassian.com/**", async route => {
    const url = new URL(route.request().url());
    const callback = new URL(url.searchParams.get("redirect_uri")!);
    callback.searchParams.set("code", "fake-code");
    callback.searchParams.set("state", url.searchParams.get("state")!);
    await route.fulfill({ status: 302, headers: { location: callback.toString() } });
  });
  await page.goto("/");
  await page.getByLabel("Email").fill("scanner-e2e@example.test");
  await page.getByLabel("Password").fill("example-password-123");
  await page.getByRole("button", { name: "Create account" }).click();
  await expect(page.getByRole("status")).toContainText("Account created");
  await page.getByRole("button", { name: "Sign in" }).click();
  await page.getByRole("button", { name: "Settings", exact: true }).click();
  await page.getByRole("button", { name: "Connect Jira" }).click();
  await page.getByLabel("Jira site").selectOption("site-one");
  await page.getByRole("button", { name: "Save site" }).click();
  await expect(page.getByText("Site selected.")).toBeVisible();
  await page.getByRole("tab", { name: "API access" }).click();
  await expect(page.getByText("Use these keys to send findings from a scanner or CI system.")).toBeVisible();
  await expect(page.getByText("Scanner endpoint:")).toBeVisible();
  await expect(page.getByText("Planned endpoint — not available:")).toHaveCount(0);
  await page.getByLabel("Key name").fill("Scanner E2E");
  await page.getByLabel("Allow ONE").check();
  await page.getByRole("button", { name: "Generate API key" }).click();
  const key = await page.getByLabel("New API key").inputValue();
  expect(key).toMatch(/^ih_/);
  await page.getByRole("button", { name: "Done" }).click();
  const data = { project: "ONE", title: "Scanner finding", description: "Fake finding", type: "identity", severity: "high", resource: "example" };
  const headers = { "x-api-key": key, "idempotency-key": "e2e-scanner-operation-1" };
  expect((await request.post("/api/v1/findings", { data })).status()).toBe(401);
  expect((await request.post("/api/v1/findings", { data: { ...data, project: "TWO" }, headers })).status()).toBe(403);
  const first = await request.post("/api/v1/findings", { data, headers });
  expect(first.status()).toBe(201);
  expect(await first.json()).toMatchObject({ issueKey: "ONE-1", url: "https://example.atlassian.net/browse/ONE-1" });
  expect(first.headers().location).toBe("https://example.atlassian.net/browse/ONE-1");
  expect((await request.post("/api/v1/findings", { data, headers })).status()).toBe(200);
  expect((await request.post("/api/v1/findings", { data: { ...data, title: "Changed" }, headers })).status()).toBe(409);
  const flattened = { project: "ONE", title: "Scanner finding", description: "Fake finding\n\nType: identity\nSeverity: high\nResource: example" };
  expect((await request.post("/api/v1/findings", { data: flattened, headers })).status()).toBe(409);
  const unknownHeaders = { ...headers, "idempotency-key": "e2e-scanner-operation-2" };
  expect((await request.post("/api/v1/findings", { data: { ...data, title: "Unknown outcome" }, headers: unknownHeaders })).status()).toBe(502);
  expect((await request.post("/api/v1/findings", { data: { ...data, title: "Unknown outcome" }, headers: unknownHeaders })).status()).toBe(409);
  await page.getByRole("button", { name: /^Revoke Scanner E2E/ }).click();
  await page.getByRole("button", { name: "Confirm revoke" }).click();
  await expect(page.getByText("Revoked", { exact: true })).toBeVisible();
  expect((await request.post("/api/v1/findings", { data, headers })).status()).toBe(401);
  expect(readFileSync(process.env.E2E_FAKE_REQUEST_LOG!, "utf8").split("\n").filter(line => line === "issue_write")).toHaveLength(2);
  await page.getByRole("button", { name: "Findings", exact: true }).click();
  await page.getByLabel("Jira project").selectOption("ONE");
  await expect(page.getByText("Scanner finding")).toBeVisible();
  await expect(page.getByRole("link", { name: /ONE-1/ })).toHaveAttribute("href", "https://example.atlassian.net/browse/ONE-1");

  await page.getByRole("button", { name: "Settings", exact: true }).click();
  await page.getByRole("tab", { name: "API access" }).click();
  await page.getByLabel("Key name").fill("Owner scanner");
  await page.getByLabel("Allow ONE").check();
  await page.getByRole("button", { name: "Generate API key" }).click();
  const ownerKey = await page.getByLabel("New API key").inputValue();
  await page.getByRole("button", { name: "Done" }).click();
  const ownerKeys = await (await page.request.get("/api/keys")).json();
  const ownerKeyId = ownerKeys.keys.find((item: { name: string }) => item.name === "Owner scanner").id;
  await page.getByRole("button", { name: "Account: scanner-e2e@example.test" }).click();
  await page.getByRole("menuitem", { name: "Sign out" }).click();
  await page.getByLabel("Email").fill("scanner-other@example.test");
  await page.getByLabel("Password").fill("example-password-123");
  await page.getByRole("button", { name: "Create account" }).click();
  await expect(page.getByRole("status")).toContainText("Account created");
  await page.getByRole("button", { name: "Sign in" }).click();
  await page.getByRole("button", { name: "Settings", exact: true }).click();
  await page.getByRole("tab", { name: "API access" }).click();
  await expect(page.getByText("No API keys yet.")).toBeVisible();
  await expect(page.getByText("Owner scanner")).toHaveCount(0);
  const otherSession = await (await page.request.get("/api/auth/session")).json();
  expect((await page.request.delete(`/api/keys/${ownerKeyId}`, { headers: { "x-csrf-token": otherSession.csrfToken } })).status()).toBe(404);
  await page.getByRole("tab", { name: "Jira connection" }).click();
  await page.getByRole("button", { name: "Connect Jira" }).click();
  await page.getByLabel("Jira site").selectOption("site-one");
  await page.getByRole("button", { name: "Save site" }).click();
  await expect(page.getByText("Site selected.")).toBeVisible();
  const ownerWrite = await page.request.post("/api/v1/findings", { data: { ...data, title: "Owner key with other cookie" }, headers: { "x-api-key": ownerKey, "idempotency-key": "e2e-scanner-owner-key-3" } });
  expect(ownerWrite.status()).toBe(201);
  await page.getByRole("button", { name: "Findings", exact: true }).click();
  await page.getByLabel("Jira project").selectOption("ONE");
  await expect(page.getByText("No tickets yet")).toBeVisible();
  await expect(page.getByText("Owner key with other cookie")).toHaveCount(0);
});
